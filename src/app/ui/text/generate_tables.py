#!/usr/bin/env python3
"""Generates UnicodeTables.cpp from Python's bundled Unicode database (no downloads).

Usage: python3 generate_tables.py > UnicodeTables.cpp

- Bidi classes: one packed uint32 per run of equal class ((start << 4) | class), embedding and
  isolate controls folded into BN. Unassigned code points get the DerivedBidiClass defaults.
- Arabic forms: compatibility decompositions of the presentation-form blocks (FE70-FEFF preferred
  over FB50-FDFF), giving each letter's isolated/final/initial/medial code point and the lam-alef
  ligatures.
"""
import unicodedata as ud

# Order must match text::BidiClass in Bidi.hpp.
CLASSES = ["L", "R", "AL", "EN", "ES", "ET", "AN", "CS", "NSM", "BN", "B", "S", "WS", "ON"]
EXPLICIT = {"LRE", "LRO", "RLE", "RLO", "PDF", "LRI", "RLI", "FSI", "PDI"}
AL_DEFAULT = [(0x0600, 0x07BF), (0x0860, 0x08FF), (0xFB50, 0xFDCF), (0xFDF0, 0xFDFF),
              (0xFE70, 0xFEFF), (0x1EC70, 0x1EFFF)]
ALEFS = (0x0622, 0x0623, 0x0625, 0x0627)
R_DEFAULT = [(0x0590, 0x05FF), (0x07C0, 0x085F), (0xFB1D, 0xFB4F), (0x10800, 0x10FFF),
             (0x1E800, 0x1EFFF)]


def bidi_class(cp):
    name = ud.bidirectional(chr(cp))
    if name == "":
        if any(lo <= cp <= hi for lo, hi in AL_DEFAULT):
            return "AL"
        if any(lo <= cp <= hi for lo, hi in R_DEFAULT):
            return "R"
        return "L"
    return "BN" if name in EXPLICIT else name


def bidi_runs():
    runs, previous = [], None
    for cp in range(0x110000):
        cls = bidi_class(cp)
        if cls != previous:
            runs.append((cp, CLASSES.index(cls)))
            previous = cls
    return runs


def arabic_forms():
    forms, lam_alef = {}, {}
    slots = {"<isolated>": 0, "<final>": 1, "<initial>": 2, "<medial>": 3}
    for block in (range(0xFE70, 0xFF00), range(0xFB50, 0xFE00)):
        for cp in block:
            parts = ud.decomposition(chr(cp)).split()
            if len(parts) < 2 or parts[0] not in slots:
                continue
            bases = [int(p, 16) for p in parts[1:]]
            slot = slots[parts[0]]
            if len(bases) == 1 and ud.category(chr(bases[0])) == "Lo":
                forms.setdefault(bases[0], [0, 0, 0, 0])
                if forms[bases[0]][slot] == 0:
                    forms[bases[0]][slot] = cp
            elif len(bases) == 2 and bases[0] == 0x0644 and bases[1] in ALEFS and slot < 2:
                lam_alef.setdefault(bases[1], [0, 0])[slot] = cp
    return sorted(forms.items()), sorted(lam_alef.items())


def main():
    runs = bidi_runs()
    forms, lam_alef = arabic_forms()
    out = ["// Generated by generate_tables.py from Unicode %s. Do not edit." % ud.unidata_version,
           "",
           '#include "app/ui/text/UnicodeTables.hpp"',
           "",
           "#include <array>",
           "",
           "namespace sloptube::app::text {",
           "namespace {",
           "",
           "constexpr std::array<std::uint32_t, %d> kBidiRunData{" % len(runs)]
    packed = ["0x%07x" % ((start << 4) | cls) for start, cls in runs]
    for i in range(0, len(packed), 8):
        out.append("    " + ", ".join(packed[i:i + 8]) + ",")
    out += ["};", "", "constexpr std::array<ArabicForms, %d> kArabicFormData{{" % len(forms)]
    for base, f in forms:
        out.append("    {0x%04x, 0x%04x, 0x%04x, 0x%04x, 0x%04x}," % (base, *f))
    out += ["}};", "", "constexpr std::array<LamAlef, %d> kLamAlefData{{" % len(lam_alef)]
    for alef, f in lam_alef:
        out.append("    {0x%04x, 0x%04x, 0x%04x}," % (alef, *f))
    out += ["}};", "", "} // namespace", "",
            "const std::span<const std::uint32_t> kBidiRuns{kBidiRunData};",
            "const std::span<const ArabicForms> kArabicForms{kArabicFormData};",
            "const std::span<const LamAlef> kLamAlef{kLamAlefData};", "",
            "} // namespace sloptube::app::text", ""]
    print("\n".join(out), end="")


if __name__ == "__main__":
    main()
